/**
 * SM-2 Spaced Repetition Update
 * quality: 1 (Again), 3 (Hard), 4 (Good), 5 (Easy)
 */
export function computeSM2Review(
  current: VocabProgress | undefined,
  wordId: string,
  quality: 1 | 3 | 4 | 5
): VocabProgress {
  const now = new Date();
  const base: VocabProgress = current || {
    wordId,
    easeFactor: 2.5,
    intervalDays: 0,
    repetitions: 0,
    nextReviewAt: now.toISOString(),
    status: 'new',
    favorite: false,
    saved: true,
  };

  let { easeFactor, intervalDays, repetitions } = base;

  if (quality < 3) {
    repetitions = 0;
    intervalDays = 1;
  } else {
    if (repetitions === 0) intervalDays = 1;
    else if (repetitions === 1) intervalDays = 6;
    else intervalDays = Math.round(intervalDays * easeFactor);
    repetitions += 1;
  }

  easeFactor = Math.max(
    1.3,
    Number((easeFactor + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02))).toFixed(2))
  );

  const nextDate = new Date(now.getTime() + intervalDays * 24 * 60 * 60 * 1000);

  let status: VocabProgress['status'] = 'learning';
  if (quality === 1) status = 'difficult';
  else if (repetitions >= 3 && easeFactor >= 2.2) status = 'mastered';

  return {
    ...base,
    easeFactor,
    intervalDays,
    repetitions,
    status,
    saved: true,
    lastReviewedAt: now.toISOString(),
    nextReviewAt: nextDate.toISOString(),
  };
}
